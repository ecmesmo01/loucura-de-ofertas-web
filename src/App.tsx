import React, { useState, useEffect, useMemo } from 'react';
import { Deal, CategoryType, StoreType } from './types';
import { INITIAL_DEALS } from './data/mockDeals';
import { Header } from './components/Header';
import { HeroBanner } from './components/HeroBanner';
import { CategoryFilter } from './components/CategoryFilter';
import { DealCard } from './components/DealCard';
import { Footer } from './components/Footer';
import { SearchX, Sparkles, RefreshCw } from 'lucide-react';

export const App: React.FC = () => {
  const [deals, setDeals] = useState<Deal[]>(INITIAL_DEALS);
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<CategoryType>('todos');
  const [selectedStore, setSelectedStore] = useState<StoreType | 'todas'>('todas');
  const [sortBy, setSortBy] = useState<'recentes' | 'desconto' | 'menor_preco'>('recentes');
  const [isRefreshing, setIsRefreshing] = useState(false);

  // Dark mode handler
  const [darkMode, setDarkMode] = useState<boolean>(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('deals_theme');
      if (saved) return saved === 'dark';
      return window.matchMedia('(prefers-color-scheme: dark)').matches;
    }
    return false;
  });

  useEffect(() => {
    if (darkMode) {
      document.documentElement.classList.add('dark');
      localStorage.setItem('deals_theme', 'dark');
    } else {
      document.documentElement.classList.remove('dark');
      localStorage.setItem('deals_theme', 'light');
    }
  }, [darkMode]);

  // Try to load any dynamic deals.json if generated by the bot in public/deals.json
  useEffect(() => {
    const fetchLatestDeals = async () => {
      try {
        const res = await fetch(`/deals.json?t=${Date.now()}`, {
          cache: 'no-store',
          headers: {
            'Cache-Control': 'no-cache, no-store, must-revalidate',
            'Pragma': 'no-cache'
          }
        });
        if (res.ok) {
          const data = await res.json();
          if (Array.isArray(data) && data.length > 0) {
            setDeals(data);
          }
        }
      } catch (e) {
        // Fallback to INITIAL_DEALS
      }
    };
    fetchLatestDeals();
  }, []);

  const handleRefresh = async () => {
    setIsRefreshing(true);
    try {
      const res = await fetch(`/deals.json?t=${Date.now()}`, {
        cache: 'no-store',
        headers: {
          'Cache-Control': 'no-cache, no-store, must-revalidate',
          'Pragma': 'no-cache'
        }
      });
      if (res.ok) {
        const data = await res.json();
        if (Array.isArray(data) && data.length > 0) {
          setDeals(data);
        }
      }
    } catch (e) {
      // Keep existing
    } finally {
      setTimeout(() => setIsRefreshing(false), 600);
    }
  };

  // Filter and sort deals
  const filteredDeals = useMemo(() => {
    let result = deals.filter((deal) => {
      // Search query
      if (searchTerm.trim()) {
        const query = searchTerm.toLowerCase();
        const matchTitle = deal.title.toLowerCase().includes(query);
        const matchDesc = deal.description?.toLowerCase().includes(query);
        const matchStore = deal.store.toLowerCase().includes(query);
        const matchCoupon = deal.couponCode?.toLowerCase().includes(query);
        if (!matchTitle && !matchDesc && !matchStore && !matchCoupon) return false;
      }

      // Category filter
      if (selectedCategory !== 'todos') {
        if (selectedCategory === 'cupons') {
          if (!deal.couponCode) return false;
        } else if (deal.category !== selectedCategory) {
          return false;
        }
      }

      // Store filter
      if (selectedStore !== 'todas') {
        if (deal.store !== selectedStore) return false;
      }

      return true;
    });

    // Sorting
    result.sort((a, b) => {
      if (sortBy === 'desconto') {
        return (b.discountPercentage || 0) - (a.discountPercentage || 0);
      }
      if (sortBy === 'menor_preco') {
        return a.currentPrice - b.currentPrice;
      }
      // 'recentes'
      return new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime();
    });

    return result;
  }, [deals, searchTerm, selectedCategory, selectedStore, sortBy]);

  return (
    <div className="min-h-screen flex flex-col bg-slate-50 dark:bg-slate-950 text-slate-800 dark:text-slate-100">
      
      {/* Top Header */}
      <Header
        searchTerm={searchTerm}
        onSearchChange={setSearchTerm}
        darkMode={darkMode}
        onToggleDarkMode={() => setDarkMode(!darkMode)}
      />

      {/* Hero Presentation */}
      <HeroBanner />

      {/* Main Content Area */}
      <main className="flex-1 max-w-7xl w-full mx-auto px-4 sm:px-6 lg:px-8 py-8">
        
        {/* Category & Store Navigation Bar */}
        <CategoryFilter
          selectedCategory={selectedCategory}
          onSelectCategory={setSelectedCategory}
          selectedStore={selectedStore}
          onSelectStore={setSelectedStore}
          sortBy={sortBy}
          onSortChange={setSortBy}
          totalOffers={filteredDeals.length}
        />

        {/* Section Heading & Refresh */}
        <div className="mt-8 mb-6 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-red-500" />
            <h2 className="text-xl sm:text-2xl font-extrabold text-slate-900 dark:text-white tracking-tight">
              {selectedCategory === 'todos' 
                ? 'Ofertas e Destaques do Dia' 
                : selectedCategory === 'cupons' 
                ? 'Ofertas com Cupom Ativo' 
                : `Ofertas em ${selectedCategory.charAt(0).toUpperCase() + selectedCategory.slice(1)}`}
            </h2>
          </div>

          <button
            onClick={handleRefresh}
            disabled={isRefreshing}
            className="inline-flex items-center gap-1.5 text-xs font-semibold px-3 py-1.5 rounded-lg bg-white dark:bg-slate-900 text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white border border-slate-200 dark:border-slate-800 transition-colors shadow-sm disabled:opacity-60"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isRefreshing ? 'animate-spin text-red-500' : ''}`} />
            <span>{isRefreshing ? 'Atualizando...' : 'Atualizar'}</span>
          </button>
        </div>

        {/* Deals Grid */}
        {filteredDeals.length > 0 ? (
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-6">
            {filteredDeals.map((deal) => (
              <DealCard key={deal.id} deal={deal} />
            ))}
          </div>
        ) : (
          /* Empty Search State */
          <div className="text-center py-20 px-4 bg-white dark:bg-slate-900 rounded-3xl border border-dashed border-slate-200 dark:border-slate-800 my-8">
            <div className="w-16 h-16 rounded-2xl bg-red-100 dark:bg-red-950/50 text-red-600 dark:text-red-400 flex items-center justify-center mx-auto mb-4">
              <SearchX className="w-8 h-8" />
            </div>
            <h3 className="text-lg font-bold text-slate-900 dark:text-white">
              Nenhuma oferta encontrada
            </h3>
            <p className="text-sm text-slate-500 dark:text-slate-400 max-w-sm mx-auto mt-1 mb-6">
              Não encontramos nenhuma oferta para os filtros selecionados. Tente buscar por outros termos ou categorias.
            </p>
            <button
              onClick={() => {
                setSearchTerm('');
                setSelectedCategory('todos');
                setSelectedStore('todas');
              }}
              className="px-5 py-2.5 rounded-xl font-bold text-sm bg-red-600 hover:bg-red-700 text-white transition-colors shadow-md shadow-red-600/20"
            >
              Limpar todos os filtros
            </button>
          </div>
        )}

      </main>

      {/* Footer */}
      <Footer />

    </div>
  );
};

export default App;
